-- Fields that are not in this database (staging, local) are skipped. A field that exists with
-- other text needs a person.
do $$
begin
  if exists (
    select 1 from pool_category_seed s join public.registry_fields f on f.id = s.field_id
    where f.source_text <> s.source_text
  ) then
    raise exception 'source-field snapshot differs; review the pool-file categories by hand';
  end if;
end $$;

insert into public.categories (name)
select distinct s.root_name from pool_category_seed s
where s.child_name is null
  and exists (select 1 from public.registry_fields f where f.id = s.field_id)
on conflict do nothing;

do $$
begin
  if exists (
    select 1 from pool_category_seed s
    join public.registry_fields f on f.id = s.field_id
    left join public.categories r on r.parent_id is null and r.name = s.root_name
    left join public.categories c on c.parent_id = r.id and c.name = s.child_name
    where r.id is null or not r.active
      or (s.child_name is not null and (c.id is null or not c.active))
  ) then
    raise exception 'a category in the pool-file mapping is missing or inactive';
  end if;
end $$;

insert into public.registry_field_categories (registry_field_id, category_id)
select s.field_id, coalesce(c.id, r.id) from pool_category_seed s
join public.registry_fields f on f.id = s.field_id
join public.categories r on r.parent_id is null and r.name = s.root_name
left join public.categories c on c.parent_id = r.id and c.name = s.child_name
on conflict (registry_field_id, category_id) do nothing;
