insert into public.org_units (name, kind, source_url)
select s.administration, 'administration',
  'https://www.jerusalem.muni.il/he/city/municipality/structure/'
from org_unit_seed s
where s.department is null
  and not exists (
    select 1 from public.org_units u
    where u.parent_id is null and lower(trim(u.name)) = lower(trim(s.administration)));

insert into public.org_units (name, kind, parent_id, source_url)
select s.department, 'department', a.id,
  'https://www.jerusalem.muni.il/he/city/municipality/structure/'
from org_unit_seed s
join public.org_units a on a.parent_id is null and a.name = s.administration
where s.department is not null
  and not exists (
    select 1 from public.org_units u
    where u.parent_id = a.id and lower(trim(u.name)) = lower(trim(s.department)));

