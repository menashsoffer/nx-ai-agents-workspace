do $$
begin
  -- A registry that exists under another name, or already has an owner, needs a person.
  if exists (
    select 1 from registry_owner_seed s join public.registries r on r.id = s.registry_id
    where r.name <> s.registry_name or r.owner_unit_id is not null
  ) then
    raise exception 'registry snapshot differs; review the registry owners by hand';
  end if;
end $$;

-- Registries that are not in this database (staging, local) are skipped.
update public.registries r
set owner_unit_id = coalesce(d.id, a.id)
from registry_owner_seed s
join public.org_units a on a.parent_id is null and a.name = s.administration
left join public.org_units d on d.parent_id = a.id and d.name = s.department
where r.id = s.registry_id and (s.department is null or d.id is not null);
